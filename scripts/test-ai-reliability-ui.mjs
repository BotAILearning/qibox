  assert.equal(await page.locator('details[data-ai-optional=reply-strategy]').getAttribute('open'), null);
  await page.locator('[name=sendImages]').check(); await page.locator('[name=sendAudio]').check(); await save();
  assert.equal(p.replyOptions.sendImages, true); assert.equal(p.replyOptions.sendAudio, true);
  assert.equal(p.customStyles.length, 0); assert.equal(p.styleId, '');
  assert.match(await page.locator('[data-ai-object-panel=reply]').innerText(), /模型服务支持.*媒体接口权限/s);
  report.checks.push('Status and strategy closed by default; opt-in image/audio options persist and explain service requirements');

  await page.locator('[data-ai-object-section=style]').click();
  await page.locator('[data-ai-style="preset:natural"]').click(); await page.locator('[name=summary]').fill('浏览器自定义甲'); await save();
  const first = p.styleId;
  report.styleSnapshots = [{ step: 'first', styles: structuredClone(p.customStyles) }];
  await page.locator('[data-ai-style="preset:polite"]').click(); await page.locator('[name=summary]').fill('浏览器自定义乙'); await save();
  report.styleSnapshots.push({ step: 'second', styles: structuredClone(p.customStyles) });
  assert.equal(p.customStyles.length, 2); assert.notEqual(p.styleId, first);
  await clickAndSave(page.locator('[data-ai-style-command=add]'));
