  bridge.contacts[2].kind = 'group'; await ai.scan();
  const person = bridge.contacts[0], group = bridge.contacts[2];
  await ai.setReplyOptions({ contact: person.id, enabled: true });
  await ai.setGroupOptions({ contact: group.id, atMe: true });
  const p = ai.profiles().find(row => row.contact === person.id), g = ai.profiles().find(row => row.contact === group.id);
