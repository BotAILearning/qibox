  const nav = async key => { await page.locator(`[data-ai-nav="${key}"]`).last().click(); await settled(); };
  const responseFor = action => page.waitForResponse(response => response.url().includes('/ai') && response.request().method() === 'POST' && response.request().postDataJSON()?.action === action);
  const save = async () => { const result = responseFor('reply-profile'); await page.locator('#ai-object-form button[type=submit]').click(); await result; await settled(); };
  const clickAndSave = async (locator, action = 'configuration') => { const result = responseFor(action); await locator.click(); await result; await settled(); };
  const confirm = page.locator('dialog.qbx-product-dialog');
  await page.goto(fixture.url); await page.locator('[data-action=open]').first().click(); await page.locator('#ai-open').click();
  await page.locator(`[data-ai-object="${person.id}"]`).click();
