  assert.equal(ai.data.replyRoundLimits.person, null);
  await page.locator('[data-ai-apply-limit-kind=person]').click(); await clickAndSave(confirm.locator('button[type=submit]'), 'apply-reply-limit');
  assert.equal(ai.data.replyRoundLimits.person, 13); assert.equal(ai.data.replyRoundLimits.group, null);
  await page.waitForFunction(() => document.body.innerText.includes('已更新'));
  report.checks.push('Bulk person cap asks confirmation, cancellation does nothing, success feedback appears and group cap is retained');

  await nav('settings'); await nav('personal-info');
  await page.locator('[name=city]').fill('深圳');
  const personalSave = page.waitForResponse(response => response.url().includes('/ai') && response.request().method() === 'POST');
  await page.locator('#ai-personal-information-form button[type=submit]').click(); await personalSave; await settled();
  assert.equal(ai.publicState().personalInformation.entries.find(row => row.field === 'city').text, '深圳');
  await nav('settings'); await nav('global-reply'); await page.locator('[name=replyGoal]').fill('直接回复当前问题，不猜测安排');
  const globalSave = page.waitForResponse(response => response.url().includes('/ai') && response.request().method() === 'POST');
  await page.locator('#ai-global-reply-form button[type=submit]').click(); await globalSave; await settled();
  assert.match(ai.globalReplyStrategy().replyGoal, /不猜测安排/);
  report.checks.push('Self-information and global strategy use their own account forms and persist through actual HTTP requests');

  await nav('activity');
  assert.equal(await page.locator('details[data-ai-optional=activity-reply]').getAttribute('open'), '');
  assert.equal(await page.locator('details[data-ai-optional=activity-skip]').getAttribute('open'), '');
  await page.locator('[data-ai-record-kind=group]').click(); await settled();
