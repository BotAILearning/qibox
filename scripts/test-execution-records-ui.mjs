import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import path from 'node:path';
import { createApplication } from '../server/index.mjs';
import { root, playwrightPath } from './tooling.mjs';
import { temp, cleanup, runtimeFactory, extractor, fetcher, packageSha256 } from '../test/fixtures.mjs';
import { ChatFixture, AIModelFixture } from '../test/ai-fixtures.mjs';
import { rfbFixture } from '../test/rfb-fixture.mjs';

const { chromium } = createRequire(import.meta.url)(playwrightPath);
const dataRoot = await temp(), bridge = new ChatFixture(), provider = new AIModelFixture();
bridge.contacts[0].avatarUrl = 'https://wx.qlogo.cn/test-avatar';
bridge.contacts[0].nickname = '微信昵称甲';
let opened = null;
bridge.openChat = async request => { opened = request.contact; return { opened: true }; };
const peer = await rfbFixture(path.join(root, 'web/backgrounds/mist.jpg'));
const app = await createApplication({ appRoot: root, dataRoot, dev: true, extract: extractor, fetcher, trustedHashes: [packageSha256], aiProvider: provider,
  runtimeFactory: (...args) => ({ ...runtimeFactory(...args), port: peer.port, aiBridge: bridge, loginStatus: 'logged-in' }) });
let browser;
try {
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  const space = await app.users.get('development');
  await space.setConsent(true); app.library.download(); await app.library.working;
  const meta = await space.add('执行记录交互检查'); await space.start(meta.id);
  const ai = space.get(meta.id).ai; clearInterval(ai.timer);
  await ai.scan();
  const contact = bridge.contacts[0];
  assert.equal(ai.publicState().contacts.find(row => row.id === contact.id)?.avatar, true);
  await ai.saveReplyProfile({ contact: contact.id, style: { summary: '简洁自然' }, strategy: { replyGoal: '回复问题' } });
  const profile = ai.profiles().find(row => row.contact === contact.id);
  const recordId = 'execution-record-avatar-ui';
  ai.data.proactiveRecords.unshift({ id: recordId, account: ai.data.account, taskId: 'archived-task', taskName: '测试任务', profileId: profile.id,
    contact: contact.id, label: contact.label, avatarUrl: contact.avatarUrl, status: 'sent', at: Date.now(), source: 'proactive', body: ai.vault.seal({ text: '测试发送内容' }) });
  await ai.save();
  assert.equal(ai.publicState().contacts.find(row => row.id === contact.id)?.avatar, true);
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/ai/avatar/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="40" height="40"><rect width="40" height="40" fill="#e26f76"/></svg>' }));
  await page.goto(`http://127.0.0.1:${app.server.address().port}${app.prefix}/?dev=${app.devKey}`);
  await page.locator('[data-action=open]').first().click();
  await page.locator('#ai-open').click();
  await page.locator('[data-ai-nav="activity"]').click();
  await page.locator('[data-ai-record-source="proactive"]').click();
  const row = page.locator(`[data-proactive-record="${recordId}"]`);
  await row.waitFor();
  await row.locator('.ai-reply-record-avatar img').evaluate(image => image.decode());
  assert.equal(await row.locator('.ai-record-contact-link .ai-contact-nick').evaluate(node => getComputedStyle(node).display), 'inline');
  assert.equal(await row.locator('[data-ai-delete-record]').count(), 0);
  await row.click({ button: 'right' });
  await page.locator('.ai-record-context-menu button').click();
  const dialog = page.locator('dialog.ai-record-delete-dialog');
  await dialog.waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await row.count(), 1);
  await row.click({ button: 'right' });
  await page.locator('.ai-record-context-menu button').click();
  await dialog.locator('[data-cancel]').click();
  assert.equal(await row.count(), 1);
  await row.click({ button: 'right' });
  await page.locator('.ai-record-context-menu button').click();
  await dialog.locator('[data-confirm]').click();
  await row.waitFor({ state: 'detached' });
  assert.equal(ai.data.proactiveRecords.some(record => record.id === recordId), false);
  const replyId = 'execution-reply-avatar-ui';
  profile.sentMessages = [{ id: replyId, source: 'reply', at: Date.now(), body: ai.vault.seal({ text: '测试自动回复' }) }];
  await ai.save();
  assert.equal(ai.publicState().contacts.find(row => row.id === contact.id)?.avatar, true);
  await page.reload();
  await page.locator('[data-action=open]').first().click();
  await page.locator('#ai-open').click();
  await page.locator('[data-ai-nav="activity"]').click();
  const identity = page.locator(`[data-ai-reply-card="${profile.id}"] [data-ai-open-conversation]`);
  await identity.waitFor();
  await identity.locator('img').waitFor({ timeout: 8000 });
  assert.equal(await identity.locator('img').count(), 1, await identity.evaluate(node => node.outerHTML));
  await identity.locator('img').evaluate(image => image.decode());
  assert.equal(await identity.locator('.ai-contact-nick').evaluate(node => getComputedStyle(node).display), 'inline');
  await page.locator(`[data-ai-reply-card="${profile.id}"] details summary`).click();
  const reply = page.locator(`[data-ai-record-menu="${replyId}"]`);
  await reply.waitFor();
  assert.equal(await reply.locator('[data-ai-delete-record]').count(), 0);
  await reply.click({ button: 'right' });
  await page.locator('.ai-record-context-menu button').click();
  await dialog.waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await reply.count(), 1);
  await reply.click({ button: 'right' });
  await page.locator('.ai-record-context-menu button').click();
  await dialog.locator('[data-confirm]').click();
  await reply.waitFor({ state: 'detached' });
  assert.equal(profile.sentMessages.some(message => message.id === replyId), true);
  assert.equal(ai.data.deletedActivityRecords?.some(item => item.id === replyId), true);
  await identity.click();
  assert.equal(opened, contact.id);
  if (errors.length) throw new Error(JSON.stringify(errors));
  console.log('PASS: both live record avatars, chat opening, right-click deletion, Escape/cancel safety, confirmed deletion');
} finally {
  await browser?.close(); await app.close(); await peer.close(); await cleanup(dataRoot);
}
