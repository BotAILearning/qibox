import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir, mkdir, writeFile, appendFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { AIModelFixture, ChatFixture, modelConfig } from './ai-fixtures.mjs';
import { temp, cleanup } from './fixtures.mjs';

const notSent = { status: 'not-sent', diagnostic: { phase: 'native-prepare', code: 'controls-unavailable' } };
const cachedText = '合成缓存答复：收到，谢谢。', nextText = '合成新来信答复：好的。';

async function fixture(t) {
  const root = await temp(), source = path.resolve(import.meta.dirname, '../server');
  const modules = (await readdir(source, { withFileTypes: true })).filter(row => row.isFile() && row.name.endsWith('.mjs')).map(row => row.name).sort();
  assert(modules.includes('ai-personal-answer.mjs'));
  const codeA = path.join(root, 'code-a', 'server'), codeB = path.join(root, 'code-b', 'server');
  for (const target of [codeA, codeB]) {
    await mkdir(target, { recursive: true });
    for (const name of modules) await writeFile(path.join(target, name), await readFile(path.join(source, name)), { flag: 'wx' });
  }
  const bridge = new ChatFixture(); bridge.stableMessageIds = true;
  await mkdir(path.join(root, 'data'));
  const provider = new AIModelFixture();
  provider.complete = async (_config, system, input) => {
    provider.calls.push({ system, input });
    assert(provider.calls.length <= 2, 'only the original incoming and a later new incoming may generate');
    return { action: 'send', text: provider.calls.length === 1 ? cachedText : nextText, followUp: false };
  };
  let clock = Date.parse('2026-10-22T20:00:00+08:00'), a;
  const load = async code => {
    const { AIAssistant } = await import(pathToFileURL(path.join(code, 'ai-service.mjs')).href);
    a = new AIAssistant({ dataRoot: path.join(root, 'data'), bridge, provider, now: () => clock, delay: async () => {}, random: min => min });
    await a.init(); clearInterval(a.timer); clearInterval(a.warmupTimer);
  };
  t.after(async () => { await a?.close(); await cleanup(root); });
  await load(codeA); await a.configure(modelConfig); await a.scan();
  const contact = bridge.contacts[0].id;
  await a.setReplyOptions({ contact, enabled: true, judgeReply: false });
  await a.settings({ enabled: true, autoLearning: false, segmentReplies: false }); await a.tick();
  const profile = () => a.profiles().find(row => row.contact === contact);
  const incoming = async text => {
    const message = bridge.push(contact, 'other', text); message.timestamp = Math.floor(clock / 1000); await a.tick(); return message;
  };
  await incoming('这条合成来信请简单回应。');
  let nativeAttempts = 0;
  const sender = bridge.send.bind(bridge);
  bridge.send = async () => { nativeAttempts++; return notSent; };
  clock += 20000; await a.tick();
  assert.equal(provider.calls.length, 1); assert.equal(nativeAttempts, 1); assert.equal(bridge.sent.length, 0);
  assert.equal(profile().preparedReply?.state, 'retry');
  assert.deepEqual(a.vault.open(profile().preparedReply.body).segments, [cachedText]);
  const old = structuredClone(profile().preparedReply);
  const resume = async ({ changedPolicy = false, changedFixedRules = false, missingPolicy = false, corruptCache = '' } = {}) => {
    if (corruptCache === 'cipher') {
      profile().preparedReply.body.data = profile().preparedReply.body.data.slice(0, -4) + 'AAAA';
      assert.throws(() => a.vault.open(profile().preparedReply.body), 'the isolated fixture must really fail authentication');
      await a.save();
    } else if (corruptCache === 'segments') {
      profile().preparedReply.body = a.vault.seal({ segments: [] });
      assert.deepEqual(a.vault.open(profile().preparedReply.body).segments, []);
      await a.save();
    }
    const file = a.file; await a.close(); a = null;
    if (missingPolicy) {
      // Emulate only the old on-disk schema. Preserve the real sealed body,
      // context/key and retry dates generated by the production pipeline.
      const data = JSON.parse(await readFile(file, 'utf8'));
      delete data.profiles[Object.keys(data.profiles).find(id => data.profiles[id].contact === contact)].preparedReply.policyFingerprint;
      await writeFile(file, JSON.stringify(data));
    }
    if (changedPolicy) await appendFile(path.join(codeB, 'ai-personal-answer.mjs'), '\n// Isolated source-only policy revision for cache compatibility test.\n');
    if (changedFixedRules) {
      const file = path.join(codeB, 'ai-reply-prompt.mjs'), source = await readFile(file, 'utf8');
      const original = 'export const replyFixedRules = `';
      assert(source.includes(original), 'the fixture must modify the real exported fixed-rule text');
      await writeFile(file, source.replace(original, original + '独立合成规则修订：只按当前资料回应。\n'));
    }
    await load(changedPolicy || changedFixedRules ? codeB : codeA);
    assert.ok(profile().preparedReply, 'initialization must leave the real persisted plan for the production retry decision');
    const currentKey = a.preparedReplyKey(profile(), a.strategy(profile(), 'reply'));
    if (changedFixedRules) assert.notEqual(profile().preparedReply.key, currentKey, 'actual fixed-rule text changes the key despite unchanged account/context/configuration');
    else assert.equal(profile().preparedReply.key, currentKey, 'configuration/context cache key is unchanged');
    bridge.send = async request => { nativeAttempts++; return sender(request); };
    clock += 30000; await a.tick();
  };
  const assertRetired = async (errorCode = 'ai_reply_policy_changed') => {
    assert.equal(nativeAttempts, 1, 'an incompatible cached plan must stop before another native attempt');
    assert.equal(bridge.sent.length, 0); assert.equal(provider.calls.length, 1, 'retirement must not regenerate the old incoming');
    assert.equal(profile().preparedReply, undefined);
    const errors = a.data.errorLog.filter(row => row.target === profile().id && row.code === 'error');
    assert(errors.some(row => row.context?.errorCode === errorCode), 'retirement needs a distinct durable failure');
    const disk = JSON.parse(await readFile(a.file, 'utf8'));
    assert.equal(disk.profiles[profile().id].preparedReply, undefined);
    assert(disk.errorLog.some(row => row.target === profile().id && row.context?.errorCode === errorCode));
    clock += 30000; await a.tick();
    assert.equal(nativeAttempts, 1); assert.equal(provider.calls.length, 1); assert.equal(bridge.sent.length, 0);
  };
  return { bridge, provider, old, resume, assertRetired, incoming, get a() { return a; }, get p() { return profile(); }, get nativeAttempts() { return nativeAttempts; }, advance: ms => { clock += ms; } };
}

test('a definite-not-sent plan is retired across helper-source policy change without regeneration or native retry', async t => {
  const f = await fixture(t); await f.resume({ changedPolicy: true }); await f.assertRetired();
});

test('an old persisted plan without a policy fingerprint is retired without regeneration or native retry', async t => {
  const f = await fixture(t); await f.resume({ missingPolicy: true }); await f.assertRetired();
});

test('same-policy restart reuses the same sealed generated answer and original retry window', async t => {
  const f = await fixture(t); await f.resume();
  assert.equal(f.provider.calls.length, 1); assert.equal(f.nativeAttempts, 2);
  assert.deepEqual(f.bridge.sent.map(row => row.text), [cachedText]); assert.equal(f.p.preparedReply, undefined);
  assert.equal(f.p.delivery.timing.completedAt, f.old.retryStartedAt + 30000);
  f.advance(30000); await f.a.tick();
  assert.equal(f.provider.calls.length, 1); assert.equal(f.nativeAttempts, 2);
});

test('after incompatible cache retirement a later incoming still generates and sends normally', async t => {
  const f = await fixture(t); await f.resume({ changedPolicy: true }); await f.assertRetired();
  await f.incoming('这是后续新的合成来信。'); f.advance(20000); await f.a.tick();
  assert.equal(f.provider.calls.length, 2); assert.equal(f.nativeAttempts, 2);
  assert.deepEqual(f.bridge.sent.map(row => row.text), [nextText]);
  f.advance(30000); await f.a.tick(); assert.equal(f.provider.calls.length, 2); assert.equal(f.nativeAttempts, 2);
});

test('a persisted definite-not-sent cache with corrupt cipher retires without regenerating the same incoming', async t => {
  const f = await fixture(t); await f.resume({ corruptCache: 'cipher' }); await f.assertRetired('ai_reply_cache_invalid');
});

test('a persisted definite-not-sent cache with invalid sealed segments retires and later incoming still works', async t => {
  const f = await fixture(t); await f.resume({ corruptCache: 'segments' }); await f.assertRetired('ai_reply_cache_invalid');
  await f.incoming('这是一条缓存退休后的新合成来信。'); f.advance(20000); await f.a.tick();
  assert.equal(f.provider.calls.length, 2); assert.equal(f.nativeAttempts, 2);
  assert.deepEqual(f.bridge.sent.map(row => row.text), [nextText]);
  f.advance(30000); await f.a.tick(); assert.equal(f.provider.calls.length, 2); assert.equal(f.nativeAttempts, 2);
});

test('a fixed-rule source change retires the cached incoming before its changed configuration key can regenerate it', async t => {
  const f = await fixture(t); await f.resume({ changedFixedRules: true }); await f.assertRetired();
});
