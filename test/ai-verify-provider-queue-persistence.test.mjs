test('explicit verification cannot block cancellation while an upstream result is still pending', async t => {
  const root = await temp(), bridge = new ChatFixture(), provider = new AIModelFixture(), a = new AIAssistant({ dataRoot: root, bridge, provider });
  t.after(async () => { await a.close(); await cleanup(root); });
  await a.init(); clearInterval(a.timer); clearInterval(a.warmupTimer); await a.configure(modelConfig);
  const entered = Promise.withResolvers(), held = Promise.withResolvers(); let requests = 0;
  provider.test = async () => { requests++; entered.resolve(); await held.promise; };
  const save = a.save; let cancellationReachedSave = false;
  a.save = function (...args) { cancellationReachedSave = true; return save.apply(this, args); };
  const verification = a.verifyProvider({ ...modelConfig, model: 'cancelled-upstream-candidate' }), outcome = verification.then(() => null, error => error);
  await entered.promise;
  let cancelled = false; const cancellation = a.cancel().then(() => { cancelled = true; });
  const saveEnteredBeforeUpstreamResult = cancellationReachedSave;
  if (saveEnteredBeforeUpstreamResult) await cancellation;
  const cancelledBeforeUpstreamResult = cancelled;
  held.resolve(); const error = await outcome; await cancellation;
  assert.equal(saveEnteredBeforeUpstreamResult, true, 'Cancellation must reach the real save method without waiting on verification');
  assert.equal(cancelledBeforeUpstreamResult, true, 'Cancellation save must not wait for the upstream verification result');
  assert.match(error?.message || '', /变化/); assert.equal(a.config.model, modelConfig.model);
  const durable = JSON.parse(await fs.readFile(a.file, 'utf8')); assert.equal(a.vault.open(durable.provider).model, modelConfig.model);
  assert.equal(requests, 1); assert.equal(provider.calls.length, 0); assert.equal(bridge.sent.length, 0);
});

for (const modern of [false, true]) for (const fail of [false, true]) test(`explicit verification ${modern ? 'modern' : 'legacy'} ${fail ? 'write failure preserves the running queue' : 'success atomically pauses the queue'} and retains the actual unsent answer`, async t => {
  const root = await temp(), bridge = new ChatFixture(), provider = new AIModelFixture(); bridge.stableMessageIds = true;
  let now = Date.parse('2026-10-22T12:00:00+08:00'), verificationRequests = 0;
  const wire = new AIProvider({ fetcher: async () => {
    verificationRequests++;
    return new Response(JSON.stringify({ choices: [{ message: { content: '{"ok":true}' } }] }), { headers: { 'content-type': 'application/json' } });
  } });
  provider.test = wire.test.bind(wire);
  const a = new AIAssistant({ dataRoot: root, bridge, provider, now: () => now, delay: async () => {}, random: min => min });
  t.after(async () => { await a.close(); await cleanup(root); });
  await a.init(); clearInterval(a.timer); clearInterval(a.warmupTimer); await a.configure(modelConfig);
  if (modern) await a.saveModels({ models: [{ ...modelConfig, id: 'verify-queue-model', label: 'Queue verification fixture' }], assignments: { chat: 'verify-queue-model', learningAnalysis: 'verify-queue-model' } });
  await a.scan(); const contact = bridge.contacts[0].id;
  await a.setReplyOptions({ contact, enabled: true, judgeReply: false }); await a.settings({ enabled: true, proactive: true, autoLearning: false }); await a.tick();
  const message = bridge.push(contact, 'other', 'Please retain this synthetic answer while verifying the model'); message.timestamp = Math.floor(now / 1000); await a.tick();
  const send = bridge.send.bind(bridge); bridge.send = () => ({ status: 'not-sent', diagnostic: { phase: 'native-prepare', code: 'fixture-verify-queue' } });
  provider.next = async () => ({ action: 'send', text: 'The already generated verification fixture answer.' });
  now += 20000; await a.tick();
  const profile = a.profiles().find(row => row.contact === contact), cached = profile.preparedReply;
  assert.equal(provider.calls.length, 1); assert.equal(cached.state, 'retry');
  const cacheBefore = structuredClone(cached), revision = a.revision, controller = a.controller;
  a.data.queue = { status: 'running', items: [{ id: profile.id, status: 'pending', attempts: 0, strategy: { ...strategy } }], nextAt: now + 3600000 };
  a.followUps.set(profile.id, { contextRevision: 'synthetic-follow-up', dueAt: now + 3600000 });
  await a.save(); const queueBefore = structuredClone(a.data.queue), save = a.save, file = a.file;
  const blocked = path.join(root, 'blocked-verification-destination'); await fs.mkdir(blocked);
  const entered = Promise.withResolvers(), held = Promise.withResolvers(); let first = true;
  a.save = function (...args) {
    if (!first) return save.apply(this, args); first = false; entered.resolve();
    return held.promise.then(async () => { if (fail) this.file = blocked; try { return await save.apply(this, args); } finally { this.file = file; } });
  };
  const operation = a.verifyProvider(modelConfig), outcome = operation.then(() => null, error => error);
  await entered.promise;
  const during = { queue: structuredClone(a.data.queue), cached: structuredClone(profile.preparedReply), revision: a.revision };
  (profile.sentMessages ||= []).push({ id: 'independent-verification-receipt', at: now });
  let ordinaryCompleted = false; const ordinary = a.save().then(() => { ordinaryCompleted = true; });
  await new Promise(resolve => setImmediate(resolve)); const completedWhilePending = ordinaryCompleted;
  held.resolve(); const error = await outcome; await ordinary;
  assert.equal(!!error, fail); if (fail) assert.ok(['EPERM', 'EISDIR', 'EACCES', 'EEXIST', 'ENOTDIR'].includes(error.code));
  assert.deepEqual(during, { queue: queueBefore, cached: cacheBefore, revision }); assert.equal(completedWhilePending, false);
  const durable = JSON.parse(await fs.readFile(file, 'utf8'));
  assert.deepEqual(a.data.queue, fail ? queueBefore : { ...queueBefore, status: 'paused', nextAt: null });
  assert.deepEqual(durable.queue, a.data.queue, 'Queue pause and model verification must be in the same durable commit');
  assert.equal(profile.preparedReply, cached); assert.deepEqual(profile.preparedReply, cacheBefore); assert.deepEqual(durable.profiles[profile.id].preparedReply, cacheBefore);
  assert.equal(a.revision, revision); assert.equal(a.controller, controller); assert.equal(controller.signal.aborted, false);
  assert.equal(a.followUps.has(profile.id), fail); assert.equal(verificationRequests, 1);
  assert.ok(durable.profiles[profile.id].sentMessages.some(row => row.id === 'independent-verification-receipt'));
  a.followUps.clear(); bridge.send = send; now += 30000; await a.tick();
  assert.equal(provider.calls.length, 1, 'Explicit verification of the same effective model must reuse the original generated answer');
  assert.deepEqual(bridge.sent.map(row => row.text), ['The already generated verification fixture answer.']);
  assert.equal(verificationRequests, 1, 'The repair must not add another verification request');
  t.diagnostic('fixture generations=1; fakeHTTP verification requests=1; fixture sends=1; real provider/WeChat calls=0');
});
